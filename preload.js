const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('oneshot', {
  readImage: (p) => ipcRenderer.invoke('image:read', p),
  siblings: (p) => ipcRenderer.invoke('image:siblings', p),
  copyImage: (buf) => ipcRenderer.invoke('clipboard:image', buf),
  copyFile: (p) => ipcRenderer.invoke('clipboard:file', p),
  saveAs: (buf, name, src) => ipcRenderer.invoke('file:save-as', buf, name, src),
  saveCopy: (src) => ipcRenderer.invoke('file:save-copy', src),
  fitWindow: (w, h) => ipcRenderer.send('window:fit', w, h),
  setFile: (p) => ipcRenderer.send('window:file', p),
  closeWindow: () => ipcRenderer.send('window:close'),
  capture: (kind) => ipcRenderer.send('capture', kind),
  openImages: () => ipcRenderer.invoke('launcher:open'),
  openFolder: () => ipcRenderer.send('open-folder'),
  openPath: (p) => ipcRenderer.send('open-path', p),
  edit: (p) => ipcRenderer.send('edit', p),
  pin: (p) => ipcRenderer.send('pin', p),
  reveal: (p) => ipcRenderer.send('reveal', p),
  dragFile: (p) => ipcRenderer.send('drag:file', p),
  dragData: (dataUrl, name) => ipcRenderer.send('drag:data', dataUrl, name),
  pathForFile: (f) => webUtils.getPathForFile(f),
  platform: process.platform,
  onMenu: (cb) => ipcRenderer.on('menu', (_e, cmd) => cb(cmd)),
  app: {
    state: () => ipcRenderer.invoke('app:state'),
    set: (key, value) => ipcRenderer.send('settings:set', key, value),
    recent: (limit) => ipcRenderer.invoke('captures:recent', limit),
    chooseDir: () => ipcRenderer.invoke('captures:choose-dir'),
    openImages: () => ipcRenderer.invoke('home:open'),
    launcher: () => ipcRenderer.send('home:launcher'),
    fixPermission: () => ipcRenderer.send('home:permission'),
    tour: () => ipcRenderer.send('home:tour'),
    tryPreview: () => ipcRenderer.send('preview:try'),
    quit: () => ipcRenderer.send('app:quit'),
    onRefresh: (cb) => ipcRenderer.on('home:refresh', () => cb()),
  },
  onboarding: {
    state: () => ipcRenderer.invoke('onboarding:state'),
    requestScreen: () => ipcRenderer.invoke('onboarding:request-screen'),
    setStep: (n) => ipcRenderer.send('onboarding:step', n),
    relaunch: () => ipcRenderer.send('onboarding:relaunch'),
    finish: () => ipcRenderer.send('onboarding:finish'),
    onStep: (cb) => ipcRenderer.on('onboarding:step', (_e, n) => cb(n)),
  },
});
